#!/usr/bin/env python3
"""Writes the translator's table of the models and textures 1.21.1 had and 26.3 doesn't (`vanilla_dropped.rs`).

A 1.21.1 mod's models name the game's own: an item model's parent (`item/template_spawn_egg`,
every 1.21.1 spawn egg's), a texture (`block/chain`). 26.3 dropped or renamed some of them (block
items draw their block's model, each spawn egg has a texture of its own, the chain is the iron
chain), and a model that names one draws nothing. The translator gives such a model the file
1.21.1 had, from the player's own 1.21.1 game (`horizon_mod_translator::vanilla_assets`): this
table says which names those are. Names only; no file of the game's is written here.

Usage: python3 tools/vanilla_dropped_assets.py <1.21.1 resources jar> <26.3 prepared resources>
  (the jar: `client-1.21.1-<stamp>-extra.jar` of a NeoForge install, beside the game's classes;
   the folder: `.local/horizon-client/26.3`)
"""
import os
import sys
import zipfile

OUT = os.path.join(os.path.dirname(os.path.abspath(__file__)), "..", "crates", "horizon-mod-translator", "src", "vanilla_dropped.rs")
ROOT = "assets/minecraft/"
# What a model or a block state names: a model by its path under `models/`, a texture by its path
# under `textures/`.
KINDS = (("models/", ".json", "MODELS"), ("textures/", ".png", "TEXTURES"))


def main():
    if len(sys.argv) != 3:
        sys.exit(__doc__)
    old = zipfile.ZipFile(sys.argv[1]).namelist()
    new = os.path.join(sys.argv[2], "assets", "minecraft")
    if not os.path.isdir(os.path.join(new, "models")):
        sys.exit(f"{new}: no models folder: not prepared resources")
    out = [
        "//! Generated by `tools/vanilla_dropped_assets.py` from the player's own games: the models and",
        "//! textures 1.21.1's `assets/minecraft/` has and 26.3's doesn't, by the name a model gives them",
        "//! (`item/template_spawn_egg`, `block/chain`). Names only. Sorted for binary search.",
        "",
    ]
    for folder, ext, name in KINDS:
        gone = sorted(
            n[len(ROOT) + len(folder) : -len(ext)]
            for n in old
            if n.startswith(ROOT + folder) and n.endswith(ext) and not os.path.exists(os.path.join(new, n[len(ROOT) :]))
        )
        out.append(f"pub(crate) const {name}: [&str; {len(gone)}] = [")
        out.extend(f'    "{g}",' for g in gone)
        out.append("];")
        out.append("")
        print(f"{name}: {len(gone)}", file=sys.stderr)
    with open(OUT, "w", encoding="utf-8", newline="\n") as f:
        f.write("\n".join(out))


if __name__ == "__main__":
    main()
