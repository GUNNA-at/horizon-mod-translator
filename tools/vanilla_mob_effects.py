#!/usr/bin/env python3
"""Writes horizon-compat's table of vanilla mob effects (`vanilla_effects.rs`) from NeoForge's merged jar.

A mod names vanilla's effects by `MobEffects` field (`MobEffects.DIG_SPEED`), and the id the field
holds (`haste`) isn't its name: `MobEffects`' static initialiser registers each effect under its id
(`register("haste", ...)`, the first string after the field before it) and stores the holder in the
field. A mod is built against the jar's version, so the table is that version's.

Needs `javap` (a JDK). Usage: python3 tools/vanilla_mob_effects.py path/to/neoforge-<version>-merged.jar
"""
import re
import subprocess
import sys

OUT = "crates/horizon-compat/src/vanilla_effects.rs"


def main():
    jar = sys.argv[1]
    text = subprocess.run(["javap", "-c", "-p", "-cp", jar, "net.minecraft.world.effect.MobEffects"], capture_output=True, text=True, check=True).stdout
    init = text[text.index("static {};") :]
    effects, first = [], None
    for line in init.splitlines():
        if (m := re.search(r"// String (\S+)$", line)) and first is None:
            first = m.group(1)
        elif m := re.search(r"putstatic .*// Field (\w+):Lnet/minecraft/core/Holder;$", line):
            if first is None:
                sys.exit(f"no id before {m.group(1)}")
            effects.append((m.group(1), first))
            first = None
    effects.sort()
    lines = [
        "//! Generated by `tools/vanilla_mob_effects.py` from NeoForge's merged jar: each `MobEffects` field and",
        "//! the effect id it registers (in `minecraft`). Sorted by field.",
        "",
        f"pub(crate) const MOB_EFFECTS: [(&str, &str); {len(effects)}] = [",
    ]
    lines += [f'    ("{f}", "{i}"),' for f, i in effects]
    lines.append("];")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(effects)} mob effects -> {OUT}")


main()
