#!/usr/bin/env python3
"""Writes horizon-compat's table of vanilla sound events (`vanilla_sounds.rs`) from NeoForge's merged jar.

A mod plays vanilla sounds by `SoundEvents` field (`SoundEvents.WOODEN_TRAPDOOR_OPEN`), and the id the
field holds (`block.wooden_trapdoor.open`) isn't its name: `SoundEvents`' static initialiser pairs each
field with the id it registers (`register("...")` for a `SoundEvent`, `registerForHolder("...")` for a
`Holder<SoundEvent>`). A mod is built against the jar's version, so the table is that
version's. The goat horn variant list is the one field that isn't a single event; it is left out.

Needs `javap` (a JDK). Usage: python3 tools/vanilla_sound_events.py path/to/neoforge-<version>-merged.jar
"""
import re
import subprocess
import sys

OUT = "crates/horizon-compat/src/vanilla_sounds.rs"


def main():
    jar = sys.argv[1]
    text = subprocess.run(["javap", "-c", "-p", "-cp", jar, "net.minecraft.sounds.SoundEvents"], capture_output=True, text=True, check=True).stdout
    init = text[text.index("static {};") :]
    events, last_id = [], None
    for line in init.splitlines():
        if m := re.search(r"// String (\S+)$", line):
            last_id = m.group(1)
        elif m := re.search(r"putstatic .*// Field (\w+):L(\S+);$", line):
            field, kind = m.group(1), m.group(2)
            if kind == "net/minecraft/sounds/SoundEvent":
                holder = False
            elif kind in ("net/minecraft/core/Holder$Reference", "net/minecraft/core/Holder"):
                holder = True
            else:
                last_id = None
                continue
            if last_id is None:
                sys.exit(f"no id before {field}")
            events.append((field, last_id, holder))
            last_id = None
    events.sort()
    lines = [
        "//! Generated by `tools/vanilla_sound_events.py` from NeoForge's merged jar: each `SoundEvents` field,",
        "//! the sound event id it registers (in `minecraft`), and whether it holds a `Holder`",
        "//! (`registerForHolder`) rather than the `SoundEvent`. Sorted by field.",
        "",
        f"pub(crate) const SOUND_EVENTS: [(&str, &str, bool); {len(events)}] = [",
    ]
    lines += [f'    ("{f}", "{i}", {str(h).lower()}),' for f, i, h in events]
    lines.append("];")
    with open(OUT, "w") as f:
        f.write("\n".join(lines) + "\n")
    print(f"{len(events)} sound events ({sum(h for _, _, h in events)} holders) -> {OUT}")


main()
